// Generates src/styles/tokens.css from docs/design-system/tokens.json.
// tokens.json is the single source of truth: never hand-copy colours into CSS.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'docs/design-system/tokens.json'), 'utf8'));

const light = [];
const dark = [];

const push = (name, value) => {
  if (value !== null && typeof value === 'object') {
    light.push(`  --${name}: ${value.light};`);
    dark.push(`  --${name}: ${value.dark};`);
  } else {
    light.push(`  --${name}: ${value};`);
  }
};

for (const group of [tokens.color, tokens.spacing, tokens.radius, tokens.shadow, tokens.size]) {
  for (const t of group.tokens) push(t.name, t.value);
}
for (const [key, stack] of Object.entries(tokens.type.families)) push(`font-${key}`, stack);

const css = `/* GENERATED by scripts/build-tokens.mjs from docs/design-system/tokens.json. Do not edit. */
:root, [data-theme="light"] {
${light.join('\n')}
}

[data-theme="dark"] {
${dark.join('\n')}
}
`;

const out = resolve(root, 'src/styles/tokens.css');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);

// Tailwind v4 theme: colours point at the CSS variables above (so data-theme switching still works);
// radii and font stacks are static in tokens.json, so they are emitted as values.
const theme = [];
for (const t of tokens.color.tokens) theme.push(`  --color-${t.name}: var(--${t.name});`);
for (const t of tokens.radius.tokens) theme.push(`  --${t.name}: ${t.value};`);
for (const [key, stack] of Object.entries(tokens.type.families)) theme.push(`  --font-${key}: ${stack};`);
for (const t of tokens.size.tokens) theme.push(`  --size-${t.name}: ${t.value};`);

writeFileSync(
  resolve(root, 'src/styles/theme.css'),
  `/* GENERATED by scripts/build-tokens.mjs from docs/design-system/tokens.json. Do not edit. */\n@theme inline {\n${theme.join('\n')}\n}\n`,
);
console.log(`tokens.css: ${light.length} light, ${dark.length} dark variables; theme.css: ${theme.length} entries`);
